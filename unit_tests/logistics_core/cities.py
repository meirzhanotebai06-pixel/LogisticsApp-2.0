def search(query: str):
    """Подстрочный поиск по KZ/RU/EN названиям (CitiesDatabase.search)."""
    if not query:
        return []
    q = query.lower()
    return [c for c in CITIES if q in c[0].lower() or q in c[1].lower() or q in c[2].lower()]


def get_city(name: str):
    n = name.strip().lower()  # FIX DEFECT-03: обрезаем пробелы по краям
    return next((c for c in CITIES if n in (c[0].lower(), c[1].lower(), c[2].lower())), None)


def is_valid(city_name: str) -> bool:
    return get_city(city_name) is not None


def get_coordinate(city_name: str):
    c = get_city(city_name)
    return (c[3], c[4]) if c else None


def parse_route(route: str):
    """Shipment.routeCoordinates: 'A → B' -> (coord_from, coord_to) или None."""
    parts = route.split(" → ")
    if len(parts) != 2:
        return None
    a, b = get_coordinate(parts[0]), get_coordinate(parts[1])
    return (a, b) if a and b else None
